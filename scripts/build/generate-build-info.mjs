#!/usr/bin/env node
/**
 * Writes `src/config/buildInfo.ts` with this checkout's Git commit and the `package.json` version.
 * Run by `bun run build` and `prepublishOnly`; the output is tracked, so expect a diff after it.
 *
 * Outside a Git checkout the commit is recorded as "unknown". A missing package version fails
 * (exit 1) instead of writing an invalid constant.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { REPO_ROOT, repoPath } from "../lib/repo-root.mjs";

const OUTPUT_FILE = repoPath("src", "config", "buildInfo.ts");

function readCommit() {
  try {
    return execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      timeout: 5000,
    }).trim();
  } catch {
    return "unknown";
  }
}

const { version } = JSON.parse(readFileSync(repoPath("package.json"), "utf8"));
if (typeof version !== "string" || !version.trim()) {
  console.error("[generate-build-info] package.json has no version; buildInfo.ts was not written.");
  process.exit(1);
}

const commit = readCommit();
writeFileSync(
  OUTPUT_FILE,
  [
    "// Generated by scripts/build/generate-build-info.mjs — do not edit manually.",
    `export const BUILD_COMMIT = ${JSON.stringify(commit)} as const;`,
    `export const APP_VERSION = ${JSON.stringify(version)} as const;`,
    "",
  ].join("\n"),
  "utf8",
);
console.log(`[generate-build-info] BUILD_COMMIT = ${commit.slice(0, 8)}, APP_VERSION = ${version}`);
